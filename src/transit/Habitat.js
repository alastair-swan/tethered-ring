import { offset_r, offset_y } from '../ring/ringGeometry.js'
import { VirtualRingObject, placeModelOnRing } from './VirtualRingObject.js'

export class virtualHabitat extends VirtualRingObject {
  static isDynamic = false

  static update(dParamWithUnits, crv) {
    const outwardOffset = dParamWithUnits['transitTubeOutwardOffset'].value - dParamWithUnits['transitTubeTubeRadius'].value + dParamWithUnits['ringTerminusOutwardOffset'].value
    const upwardOffset = dParamWithUnits['transitTubeUpwardOffset'].value + dParamWithUnits['ringTerminusUpwardOffset'].value
    virtualHabitat.habitatOutwardOffset = dParamWithUnits['habitatOutwardOffset'].value
    virtualHabitat.habitatUpwardOffset = dParamWithUnits['habitatUpwardOffset'].value
    virtualHabitat.habitatForwardOffset = dParamWithUnits['habitatForwardOffset'].value
    virtualHabitat.habitatRelativePosition_r = offset_r(outwardOffset, upwardOffset, crv.currentEquivalentLatitude)
    virtualHabitat.habitatRelativePosition_y = offset_y(outwardOffset, upwardOffset, crv.currentEquivalentLatitude)
    virtualHabitat.currentEquivalentLatitude = crv.currentEquivalentLatitude
    virtualHabitat.isVisible = dParamWithUnits['showHabitats'].value
  }

  placeAndOrientModel(om, refFrame) {
    placeModelOnRing(om, refFrame.curve, this.trackPosition(refFrame),
      virtualHabitat.habitatRelativePosition_r, virtualHabitat.habitatRelativePosition_y, 0,
      virtualHabitat.currentEquivalentLatitude)
    om.rotateZ(-Math.PI/2)
    om.rotateY(-Math.PI/2)
    om.visible = virtualHabitat.isVisible
    // The first five children are the bubble, stairwell and floors generated by generateHabitatMeshes().
    const f = virtualHabitat.habitatForwardOffset
    const u = virtualHabitat.habitatUpwardOffset
    const o = virtualHabitat.habitatOutwardOffset
    for (let i = 0; i < Math.min(5, om.children.length); i++) {
      const child = om.children[i]
      const extraUp = (child.userData && child.userData['upwardOffset']) || 0
      child.position.set(f, u + extraUp, o)
    }
  }
}
