import * as THREE from 'three'
import * as tram from '../utils/tram.js'
import * as kmlutils from '../export/kmlutils.js'
import { placeAtHeightInRingPlane, ringPlaneOffset } from './ringGeometry.js'

export class mainRingCurve {
    constructor(dParamWithUnits, planetSpec, crv, index, genKMLFile, kmlFile, ringToPlanetQuaternion) {

    this.curveControlPoints = this.generateMainRingControlPoints(dParamWithUnits, crv, planetSpec, ringToPlanetQuaternion)
  
    const mainRingCurve = new THREE.CatmullRomCurve3(this.curveControlPoints)
    mainRingCurve.curveType = 'centripetal'
    mainRingCurve.closed = true
    mainRingCurve.tension = 0
    // How far the ring's plane was moved along its axis (see generateMainRingControlPoints).
    mainRingCurve.planeOffset = this.planeOffset
  
    // KML for the main ring is generated by tetheredRingSystem (it knows the ring's orientation).

    return mainRingCurve
  
  }
  
  // The ring is designed on a sphere of the equatorial radius, then its plane is moved along its axis
  // and each point is moved in the plane, towards or away from the axis, to the ring's height above sea
  // level (the ellipsoid). The ring stays in one plane, as an ellipse of low eccentricity (the plane's
  // section of the flattened planet), and is at a constant height. (A ring of constant gravity would be a better design, but
  // needs the planet's gravity field.)
  generateMainRingControlPoints(dParamWithUnits, crv, planetSpec, ringToPlanetQuaternion) {
  
    const n = dParamWithUnits['numControlPoints'].value
    const e = dParamWithUnits['ringEccentricity'].value
  
    const controlPoints = []
    const roughPlanetRadius = planetSpec.ellipsoid.a
    this.planeOffset = ringToPlanetQuaternion ? ringPlaneOffset(crv, ringToPlanetQuaternion, planetSpec.ellipsoid) : 0

    // const centerOfRing = new THREE.Vector3(0, crv.yc, 0).applyQuaternion(ringToPlanetRotation)
    // const lengthOfSiderealDay = 86160 // s
    // const Ω = new THREE.Vector3(0, -2 * Math.PI / lengthOfSiderealDay, 0)
  
    for (let a = 0, i = 0; i<n; a += Math.PI*2/n, i++) {
      const angleInRingCoordSys = Math.acos(crv.mainRingRadius / (roughPlanetRadius + crv.currentMainRingAltitude)) * Math.sqrt((e*Math.cos(a))**2 + (1/e*Math.sin(a))**2)
      const rInRingCoordSys = (roughPlanetRadius + crv.currentMainRingAltitude) * Math.cos(angleInRingCoordSys)
      const positionInRingCoordSys = new THREE.Vector3()
      positionInRingCoordSys.y = (roughPlanetRadius + crv.currentMainRingAltitude) * Math.sin(angleInRingCoordSys)
      positionInRingCoordSys.x = rInRingCoordSys * Math.cos(a)
      positionInRingCoordSys.z = rInRingCoordSys * Math.sin(a)
      if (ringToPlanetQuaternion) placeAtHeightInRingPlane(positionInRingCoordSys, crv.currentMainRingAltitude, ringToPlanetQuaternion, planetSpec.ellipsoid, this.planeOffset)
      controlPoints.push(positionInRingCoordSys)
    }

    return controlPoints

  }
  
  // Kept for backward compatibility; use genMainRingKML() (needs the ring's orientation).
  genKML() {
    console.warn('mainRingCurve.genKML is deprecated; tetheredRingSystem generates the main ring KML (see genMainRingKML).')
    return ''
  }
}

// Returns a KML <Placemark> (LineString) tracing the main ring.
// curve: the main ring curve (tetheredRingRefCoordSys-local); ringToPlanetQuaternion: the rotation
// from ring-local to planet-local coordinates (tetheredRingSystem.ringToPlanetQuaternion).
export function genMainRingKML(curve, planetSpec, ringToPlanetQuaternion, numPoints = 8192) {
  const points = curve.getPoints(numPoints)
  let kml = kmlutils.kmlMainRingPlacemarkHeader
  let firstCoordString = ''
  const xyzPlanet = new THREE.Vector3()
  points.forEach((point, i) => {
    xyzPlanet.copy(point).applyQuaternion(ringToPlanetQuaternion)
    const lla = tram.ecefToGeodetic(xyzPlanet.x, xyzPlanet.y, xyzPlanet.z, planetSpec.ellipsoid)
    const coordString = '          ' + Math.round(lla.lon*10000000)/10000000 + ',' + Math.round(lla.lat*10000000)/10000000 + ',' + Math.round(Math.abs(lla.alt)*1000)/1000 + '\n'
    if (i==0) firstCoordString = coordString
    kml += coordString
  })
  kml += firstCoordString  // Repeat the first coordinate to close the loop
  kml += kmlutils.kmlPlacemarkFooter
  return kml
}
